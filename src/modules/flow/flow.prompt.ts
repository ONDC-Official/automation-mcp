/**
 * The persona and the loop discipline.
 *
 * Everything else in this server is designed so a model *can* drive a
 * transaction. These prompts are what make it drive one *well*, and they exist
 * because three mistakes account for almost every failed run:
 *
 * 1. **Polling instead of waiting.** `flow_get_status` in a loop burns context
 *    and still misses callbacks. `flow_await` blocks properly and reports what
 *    arrived.
 * 2. **Reading whole payloads.** One `on_search` catalog can evict everything
 *    the model needs to finish the flow. Handles and JSONPath slices exist for
 *    exactly this.
 * 3. **Treating a NACK as a crash.** A rejected payload is the most
 *    informative result a compliance test produces. It is the finding, not an
 *    error to route around.
 *
 * The two prompts differ only in which side the model plays, but the difference
 * is worth stating explicitly: which steps are yours, and which you wait for,
 * is the one thing that decides whether the loop moves or hangs.
 *
 * ## What the session journal changed here
 *
 * These used to describe a loop in which the model had to *ask* about
 * everything, and remember a `seq` to ask correctly. It no longer does. Steps
 * that need nothing send themselves, and every tool result carries what has
 * happened since the last one — so the discipline being taught is now: read
 * `events`, wait on the whole session when idle, and spend your turns on the
 * parts that need judgement. Saying that plainly matters more than any single
 * tool description, because a model that keeps polling gets a correct but far
 * more expensive run.
 */

const LOOP = `
## The loop

1. \`receiver_start\` — get the callback URL, and check the participant can
   actually reach it. A loopback URL only works for a participant on this
   machine.
2. \`session_create\` — the participant's subscriber URL and whether it is a BAP
   or a BPP. This server takes the opposite role automatically.
3. \`catalog_list_flows\` — pick a flow. \`catalog_describe_flow\` shows who owns
   each step.
4. \`flow_start\` — opens the run. Give the participant the \`callback_url\` it
   returns before going further: that is the URI to register as this mock's
   subscriber URL, and the participant appends \`/{action}\` to it the same way
   it would for any network participant.
5. Then repeat until \`COMPLETE\`, naming the run with \`session_id\` +
   \`flow_id\`:
   - \`flow_proceed\` when the next step is yours **and needs something from
     you** — a value, a decision, a form.
   - \`flow_await\` **with no flow named** when you have nothing to do. That
     watches the whole session and comes back the moment anything happens on any
     run. Name a \`flow_id\` only when you genuinely care about one run and not
     the others.
   - \`form_fetch\` / \`form_submit\` when a form step comes up.
6. Read the outcome's \`outcome\` field and do what it says. Every tool answer
   ends by naming the tool to call next.

## Most steps send themselves

A step of yours that needs no input is sent for you, as soon as the step before
it lands. You will not be asked to approve it, and you do not need to: it was
generated by the flow's own published config, and asking would be a question
with one possible answer.

**So do not go looking for work.** Your turns are for the things that need
judgement — supplying inputs, filling forms, reading what came back, and saying
whether it was compliant.

## \`events\`: read it on every result

Every answer carries an \`events\` block when something has happened since your
last call: callbacks that arrived, steps sent for you (\`CHAIN_SENT\`), refusals,
forms submitted, a flow completing. Each event is delivered **exactly once**, on
whatever tool you happened to call next — so read it when it appears, because
the next result will not repeat it.

- \`more\` above zero means there were too many for one result. Call
  \`record_get_events\` for the rest.
- \`record_get_events\` also re-reads anything already delivered, which is how you
  recover if you lost a result.
- \`CHAIN_PAUSED\` is the important one: it means the automatic sending stopped
  and is waiting on you. Its summary says what for.
- \`ISSUE_OPEN\` means something went wrong and has been recorded. Answer it with
  \`feedback_submit_report\` once you know what happened — see below.

## When something goes wrong, say what you made of it

Every refusal, block and failed send is captured automatically, with the payload
values stripped out. What is *not* captured is the part only you know: what you
thought was wrong, what you tried, and whether it worked.

So when a result carries an \`ISSUE_OPEN\` event, call \`feedback_submit_report\`
with that \`incident_id\` — **after** you have tried to resolve it, so you can say
how it turned out. Report it whether or not you fixed it; a run you could not
rescue is the more useful of the two.

Two things worth knowing. Its \`tooling_gap\` field — "what would have let you
resolve this faster" — is the most valuable thing you can write, because it is
what changes the tools you are given next time. And **do not paste payload
values into any field**; name the JSONPath instead. Report values are stripped
either way, so pasting one only costs you the sentence it was in.

Do not stop the flow to file a report, and do not file one before you have
attempted the fix. One report per incident: repeats of the same failure are
counted for you.

## Rules that matter

- **Never poll \`flow_get_status\` in a loop.** \`flow_await\` blocks server-side
  and wakes on the callback. Read status when you have lost track, not to wait.
- **When idle, wait on the session, not on one run.** \`flow_await\` with neither
  \`flow_id\` nor \`transaction_id\` needs no \`seq\` bookkeeping — the server tracks
  what you have been shown — and it returns \`runs\`, a line per flow telling you
  where each stands and which to pick up next. Waiting on a single run makes you
  deaf to everything else in the session.
- **Never fetch a whole payload to look at one field.** Pass a \`jsonpath\` to
  \`record_get_payload\`. A catalog can be hundreds of kilobytes and will crowd
  out everything you need to finish.
- **A NACK is a result, not a failure.** If the participant rejects a payload,
  that is the finding — record what it said and carry on. Only an unreachable
  participant is an error.
- **BLOCKED means read \`details\`.** \`requirements_not_met\` almost always means
  an earlier step did not supply something; \`record_get_data\` shows what the
  flow has actually saved.
- **Do not invent identifiers.** Transaction and message ids are generated for
  you, and submission ids come from whoever issued them.
- **A run has no \`transaction_id\` until its first action crosses the wire.**
  That id belongs to whoever sends the flow's first action — when the
  participant moves first it is theirs to choose, and \`flow_start\` returns
  \`null\`. Address the run by \`flow_id\`; the id appears in the answer to
  whichever call learns it, and you can use either from then on.
- **If the flow will not advance**, call \`flow_get_status\` and read
  \`missed_steps\` — an exchange that arrived out of sequence is recorded there
  rather than silently dropped.
- **To try a run again, call \`flow_restart\` — never \`session_create\`.** A
  flow's state is replayed from what was exchanged, so a botched step stays in
  the history and \`flow_start\` would only resume it. \`flow_restart\` abandons
  the attempt and opens a fresh one in the same session; the old attempt's
  payloads stay readable, so nothing you need for the report is lost. Starting a
  second session instead leaves the first one still listening on the endpoint
  every session shares, where it competes for the participant's callbacks.
`;

const INPUTS = `
## Supplying inputs

When a step comes back \`INPUT_REQUIRED\`, its \`inputs_required.fields\` lists the
keys it wants. In an \`llm_auto\` session, choose plausible test values yourself
and pass them as \`inputs\`. In a \`manual\` session, ask the person driving the
test and pass what they give you.

\`inputs\` is **flat**: it becomes \`sessionData.user_inputs\` verbatim, and the
step's generator reads those field names straight off it. Send
\`{"city_code": "std:011"}\`, never \`{"SomeInputId": {"city_code": "std:011"}}\` —
a declaration's name is not a key to nest under. \`inputs_required.example\`
shows the shape when the flow declares one.

A step marked manual only fires when you name it: pass
\`inputs: {"id": "<step_key>"}\`. That gate is deliberate — it exists so those
steps cannot go out as a side effect of a generic "proceed".
`;

function persona(role: "buyer" | "seller"): string {
  const [playing, against] =
    role === "buyer"
      ? ["a buyer app (BAP)", "a seller app (BPP)"]
      : ["a seller app (BPP)", "a buyer app (BAP)"];

  const ownership =
    role === "buyer"
      ? "You send `search`, `select`, `init`, `confirm`, `status` and the other buyer-side calls; you wait for every `on_…` the seller answers with."
      : "You send `on_search`, `on_select`, `on_confirm` and the other seller-side callbacks; you wait for the buyer's `search`, `select`, `confirm` and so on.";

  return `You are driving a mock ${playing} on the ONDC network, testing a real
${against} for protocol compliance.

Payloads are generated for you from the flow's own published mock config — you
do not write beckn JSON by hand, and steps that need nothing from you are sent
without being asked. Your job is to supply the values the flow asks for, fill
the forms it puts in front of you, and judge what comes back.

${ownership} \`flow_get_status\` marks every step \`us\` or \`np\` if you are unsure.
${LOOP}${INPUTS}
## When the flow completes

Say what happened: which steps completed, which were NACKed and why, and
anything in \`missed_steps\`. That summary is the point of the exercise — the
transaction itself is only the means.`;
}

const PromptArgs = z.object({});

function definePrompt(
  name: string,
  title: string,
  description: string,
  text: string,
): Registerable {
  return {
    name,
    register(server: McpServer): void {
      server.registerPrompt(
        name,
        { title, description, argsSchema: PromptArgs },
        () => ({
          messages: [{ role: "user", content: { type: "text", text } }],
        }),
      );
    },
  };
}

export function createFlowPrompts(): Registerable[] {
  return [
    definePrompt(
      "mock_buyer",
      "Drive as a mock buyer app",
      "Persona and loop discipline for testing a seller app (BPP): this server " +
        "plays the buyer, sends the buyer-side calls, and waits for the seller's callbacks.",
      persona("buyer"),
    ),
    definePrompt(
      "mock_seller",
      "Drive as a mock seller app",
      "Persona and loop discipline for testing a buyer app (BAP): this server " +
        "plays the seller, answers with the seller-side callbacks, and waits for the buyer's calls.",
      persona("seller"),
    ),
  ];
}
